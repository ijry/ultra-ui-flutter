/// Global entry similar to uni.`$u`.
class UP {
  UP._();

  static final UPConfig configStore = UPConfig();

  static UPConfigData get config => configStore.config;
  static UPColorData get color => configStore.color;
  static UPZIndexData get zIndex => configStore.zIndex;
  static UPPropsData get props => configStore.props;

  static void setConfig({
    UPConfigData? config,
    UPColorData? color,
    UPZIndexData? zIndex,
    UPPropsData? props,
  }) {
    configStore.merge(
      config: config,
      color: color,
      zIndex: zIndex,
      props: props,
    );
  }

  static double getPx(dynamic value, {bool unit = false, double? screenWidth}) {
    return UPUtils.getPx(value, unit: unit, screenWidth: screenWidth);
  }

  static double rpx2px(num value, {double? screenWidth}) {
    return UPUtils.rpx2px(value, screenWidth: screenWidth);
  }

  static double range(num min, num max, num value) =>
      UPUtils.range(min, max, value);

  static Future<void> sleep([int ms = 30]) => UPUtils.sleep(ms);

  static final test = UPTest();

  static void toast(
    BuildContext context, {
    String message = '',
    String type = '',
    String icon = '',
    bool loading = false,
    String position = 'center',
    int duration = 2000,
  }) {
    UPToast.show(
      context,
      message: message,
      type: type,
      icon: icon,
      loading: loading,
      position: position,
      duration: duration,
    );
  }

  static void hideToast() => UPToast.hide();

  static ThemeData themeData({Brightness brightness = Brightness.light}) {
    final tokens = brightness == Brightness.dark
        ? UPThemeTokens.dark()
        : UPThemeTokens.light();
    return ThemeData(
      brightness: brightness,
      primaryColor: tokens.primary,
      scaffoldBackgroundColor: tokens.pageBgColor,
      extensions: <ThemeExtension<dynamic>>[tokens],
    );
  }
}
